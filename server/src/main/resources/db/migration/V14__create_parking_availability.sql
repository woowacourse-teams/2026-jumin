create table parking_availability_mappings
(
    id               bigint generated by default as identity primary key,
    parking_lot_id   bigint       not null references parking_lots (id),
    provider         varchar(20)  not null check (provider in ('SEOUL', 'BUSAN')),
    external_id      varchar(100) not null,
    expected_name    text         not null,
    expected_address text         not null,
    unique (provider, external_id),
    unique (parking_lot_id, provider)
);

create table parking_availability
(
    parking_lot_id    bigint primary key references parking_lots (id),
    provider          varchar(20)  not null check (provider in ('SEOUL', 'BUSAN')),
    external_id       varchar(100) not null,
    capacity          integer      not null,
    occupied          integer      not null,
    available         integer      not null,
    source_updated_at timestamptz,
    fetched_at        timestamptz  not null,
    check (capacity > 0 and occupied between 0 and capacity and available between 0 and capacity
        and occupied::bigint + available = capacity
)
    );

create table parking_availability_history
(
    id                bigint generated by default as identity primary key,
    parking_lot_id    bigint       not null references parking_lots (id),
    provider          varchar(20)  not null check (provider in ('SEOUL', 'BUSAN')),
    external_id       varchar(100) not null,
    observation_key   text         not null,
    capacity          integer      not null,
    occupied          integer      not null,
    available         integer      not null,
    source_updated_at timestamptz,
    fetched_at        timestamptz  not null,
    unique (parking_lot_id, provider, external_id, observation_key),
    check (capacity > 0 and occupied between 0 and capacity and available between 0 and capacity
        and occupied::bigint + available = capacity
)
    );
