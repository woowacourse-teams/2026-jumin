delete
from parking_availability_mappings m using availability_mapping_seed s, parking_lots p
where s.exclusion_reason is not null
  and m.provider = s.provider
  and m.external_id = s.external_id
  and m.parking_lot_id = p.id
  and btrim(p.name) = s.parking_name
  and btrim(p.address) = s.parking_address
  and m.expected_name = s.parking_name
  and m.expected_address = s.parking_address;

delete
from parking_availability_mappings m using parking_lots p
where m.parking_lot_id = p.id
  and exists (select 1 from availability_mapping_seed s
    where s.provider = m.provider
  and s.external_id = m.external_id)
  and (not p.active
   or btrim(p.name) is distinct from m.expected_name
   or btrim(p.address) is distinct from m.expected_address);

create
temporary table availability_mapping_candidates on commit drop
as
select provider, external_id, parking_lot_id, parking_name, parking_address
from (select s.provider,
             s.external_id,
             p.id as      parking_lot_id,
             s.parking_name,
             s.parking_address,
             row_number() over (
               partition by s.provider, s.external_id
               order by (m.id is not null) desc,
                        (btrim(p.name) = btrim(s.facility_name)) desc nulls last,
                        p.id
           ) as priority
      from availability_mapping_seed s
               join parking_lots p on p.active = true
          and btrim(p.name) = s.parking_name and btrim(p.address) = s.parking_address
               left join parking_availability_mappings m on m.parking_lot_id = p.id
          and m.provider = s.provider and m.external_id = s.external_id
          and m.expected_name = s.parking_name and m.expected_address = s.parking_address
      where s.exclusion_reason is null) ranked
where priority = 1;

insert into parking_availability_mappings
(parking_lot_id, provider, external_id, expected_name, expected_address)
select parking_lot_id, provider, external_id, parking_name, parking_address
from availability_mapping_candidates
where true on conflict do nothing;

select sources.provider,
       count(*) as eligible_sources,
       count(*)    filter (where m.id is not null) as mapped, count(*) filter (where m.id is null and c.parking_lot_id is null) as missing, count(*) filter (where m.id is null and c.parking_lot_id is not null) as conflicting
from (select distinct provider, external_id
      from availability_mapping_seed
      where exclusion_reason is null) sources
         left join parking_availability_mappings m
                   on m.provider = sources.provider and m.external_id = sources.external_id
         left join availability_mapping_candidates c
                   on c.provider = sources.provider and c.external_id = sources.external_id
group by sources.provider
order by sources.provider;

commit;
